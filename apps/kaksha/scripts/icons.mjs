const out = {};
for (const [name, file] of Object.entries(ICONS)) {
  const svg = readFileSync(path.join(dir, `${file}.svg`), "utf8");
  const els = [];
  for (const m of svg.matchAll(
    /<(path|circle|rect|line|polyline|polygon|ellipse)\s([^>]*?)\/?>/g,
  )) {
    const attrs = {};
    for (const a of m[2].matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    // Tabler's invisible bounding-box path.
    if (attrs.stroke === "none" && attrs.d === "M0 0h24v24H0z") continue;
    els.push([m[1], attrs]);
  }
  out[name] = els;
}
const body = `// Generated by scripts/icons.mjs from Tabler Icons (MIT, https://tabler.io/icons). Do not edit.
export type IconEl = [string, Record<string, string>];
export const ICON_DATA = ${JSON.stringify(out)} as const satisfies Record<string, readonly IconEl[]>;
export type IconName = keyof typeof ICON_DATA;
`;
writeFileSync(path.join(app, "src", "icons.ts"), body);
