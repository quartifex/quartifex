#!/usr/bin/env python3
"""AVENUE logo set (run by hand: python3 scripts/brand.py; needs fontTools and brotli): the lane mark, its small-size cut, the outlined wordmark, the horizontal
lockup and the app icon. All single-ink SVG (currentColor) except the icon.

The mark: two lanes converge to a vanishing point and form an A; the stop line across both
lanes is the A's bar, broken where the centre line runs. Under 24 px the stop line is dropped
(it fills in), which is the small cut.
"""
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

APP = Path(__file__).resolve().parent.parent
OUT = APP / "public" / "brand"
OUT.mkdir(exist_ok=True)
FONT = APP / "node_modules/@fontsource-variable/archivo/files/archivo-latin-wdth-normal.woff2"

# Mark geometry in a 120 x 120 box; the drawing spans x 10..110, y 6..112.
LANES = [
    "M10 112 L26 112 L59.2 6 L58.4 6 Z",
    "M94 112 L110 112 L61.6 6 L60.8 6 Z",
]
STOP_LINE = [
    "M33.5 76 L55.5 76 L55.5 80.5 L32.1 80.5 Z",
    "M64.5 76 L86.5 76 L87.9 80.5 L64.5 80.5 Z",
]
CENTRE_FULL = [
    "M57.2 112 L62.8 112 L61.9 92 L58.1 92 Z",
    "M59.3 62 L60.7 62 L60.4 50 L59.6 50 Z",
]
CENTRE_SMALL = [
    "M57.2 112 L62.8 112 L61.7 90 L58.3 90 Z",
    "M58.6 78 L61.4 78 L60.9 63 L59.1 63 Z",
    "M59.4 54 L60.6 54 L60.3 45 L59.7 45 Z",
]
MARK_FULL = LANES + STOP_LINE + CENTRE_FULL
MARK_SMALL = LANES + CENTRE_SMALL


def svg(viewbox: str, body: str, label: str = "AVENUE") -> str:
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{viewbox}" role="img" '
        f'aria-label="{label}"><title>{label}</title>{body}</svg>\n'
    )


def paths(ds, fill="currentColor", transform=None):
    t = f' transform="{transform}"' if transform else ""
    return f'<g fill="{fill}"{t}>' + "".join(f'<path d="{d}"/>' for d in ds) + "</g>"


# Crop the mark to its drawn extent: x 10..110 (100 wide), y 6..112 (106 tall).
(OUT / "avenue-mark.svg").write_text(svg("10 6 100 106", paths(MARK_FULL)))
(OUT / "avenue-mark-small.svg").write_text(svg("10 6 100 106", paths(MARK_SMALL)))

# Wordmark: Archivo, wide and light, tracked open.
font = instantiateVariableFont(TTFont(FONT), {"wdth": 125, "wght": 380})
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
cap = font["OS/2"].sCapHeight
upm = font["head"].unitsPerEm
tracking = 0.18 * upm
pen = SVGPathPen(glyphs)
x = 0.0
word = "AVENUE"
for i, ch in enumerate(word):
    name = cmap[ord(ch)]
    glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, cap)))
    x += glyphs[name].width + (tracking if i < len(word) - 1 else 0)
word_w = round(x)
word_d = pen.getCommands()
(OUT / "avenue-wordmark.svg").write_text(
    svg(f"0 0 {word_w} {cap}", f'<path fill="currentColor" d="{word_d}"/>')
)

# Lockup: the mark 1.5 cap heights tall, baseline-aligned, a gap of one cap height.
mark_h = cap * 1.5
scale = mark_h / 106
mark_w = 100 * scale
gap = cap * 0.95
total_w = mark_w + gap + word_w
mark_g = paths(MARK_FULL, transform=f"translate({-10 * scale:.2f} {cap - mark_h - 6 * scale:.2f}) scale({scale:.4f})")
word_g = f'<path fill="currentColor" transform="translate({mark_w + gap:.2f} 0)" d="{word_d}"/>'
top = cap - mark_h
(OUT / "avenue-lockup.svg").write_text(
    svg(f"0 {top:.2f} {total_w:.2f} {mark_h:.2f}", mark_g + word_g)
)

# App icon: the small cut in ice on asphalt, a squircle-ish tile.
icon = (
    '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128" role="img" aria-label="AVENUE">'
    '<title>AVENUE</title><rect width="128" height="128" rx="28" fill="#06070a"/>'
    + paths(MARK_SMALL, fill="#e9eef7", transform="translate(18 21) scale(0.92)")
    + "</svg>\n"
)
(OUT / "avenue-icon.svg").write_text(icon)
(APP / "src/app/icon.svg").write_text(icon)
# Path data for the inline logo component (src/components/Logo.tsx).
ts = (
    "// Generated by scripts/brand.py. Do not edit by hand.\n"
    f"export const MARK = {MARK_FULL!r};\n".replace("'", '"')
    + f"export const MARK_SMALL = {MARK_SMALL!r};\n".replace("'", '"')
    + f'export const WORD = {{ d: "{word_d}", width: {word_w}, height: {cap} }};\n'
)
(APP / "src/components/logo-paths.ts").write_text(ts)
# The old placeholder path stays valid: avenue-logo.svg is the lockup.
(OUT / "avenue-logo.svg").write_text((OUT / "avenue-lockup.svg").read_text())
print("wordmark", word_w, "x", cap, "| lockup", round(total_w), "x", round(mark_h))
